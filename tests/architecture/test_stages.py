"""The registry and the generated `dvc.yaml` (D1 §9.2, §9.5, §13; D3 §10.1)."""

from pathlib import Path, PurePosixPath
from typing import Any

import yaml

from energatron.core.models.catalog import CATALOG_FILENAME, SourceType
from energatron.services.stages.dvc_yaml import CODE_FINGERPRINT_PATH, emit_dvc_yaml
from energatron.services.stages.registry import STAGES

GOLDEN = Path(__file__).resolve().parents[1] / "fixtures" / "golden" / "dvc.yaml"
HEADER = "# Generated by energatron pipeline sync. Do not edit; re-run the command instead.\n"


def generated() -> dict[str, dict[str, Any]]:
    return yaml.safe_load(emit_dvc_yaml(STAGES))["stages"]


def test_generated_dvc_yaml_equals_the_golden_file() -> None:
    # Changing the golden file is a deliberate part of any change to STAGES (D1 §9.5).
    assert emit_dvc_yaml(STAGES) == GOLDEN.read_text(encoding="utf-8")


def test_dvc_yaml_starts_with_the_generated_header() -> None:
    assert emit_dvc_yaml(STAGES).startswith(HEADER)


def test_every_registered_stage_is_emitted_with_its_command() -> None:
    stages = generated()
    assert list(stages) == list(STAGES)
    for name, entry in stages.items():
        assert entry["cmd"] == f"energatron stage {name}"


def test_registry_keys_are_the_spec_names() -> None:
    assert all(name == spec.name for name, spec in STAGES.items())


def test_outputs_are_directories_and_nothing_disables_the_cache() -> None:
    text = emit_dvc_yaml(STAGES)
    assert "cache:" not in text
    for name, entry in generated().items():
        outs = entry["outs"]
        assert outs == list(STAGES[name].outputs.values())
        for out in outs:
            assert isinstance(out, str)  # a plain path: no per-output options such as `cache: false`
            assert PurePosixPath(out).suffix == ""
            assert not out.startswith("data/raw/")


def test_deps_are_the_declared_inputs_as_concrete_paths() -> None:
    for name, entry in generated().items():
        deps = entry.get("deps", [])
        assert deps == list(STAGES[name].inputs.values())
        for dep in deps:
            assert isinstance(dep, str)
            assert not any(char in dep for char in "*?[]{}")
            assert dep != "uv.lock" and dep != CODE_FINGERPRINT_PATH
            assert not dep.startswith("/") and ".." not in dep.split("/")


def test_each_stage_tracks_exactly_its_own_code_entry() -> None:
    for name, entry in generated().items():
        params = entry["params"]
        assert isinstance(params, list)
        plain = [item for item in params if isinstance(item, str)]
        files = [item for item in params if isinstance(item, dict)]
        assert plain == list(STAGES[name].params)
        assert files == [{CODE_FINGERPRINT_PATH: [f"stages.{name}.stage_sha256"]}]
        assert "uv.lock" not in plain


def test_per_source_inputs_cover_every_source_type() -> None:
    for spec in STAGES.values():
        prefixes = {name.partition(".")[0] for name in spec.inputs if "." in name}
        for prefix in prefixes:
            sources = sorted(name.partition(".")[2] for name in spec.inputs if name.startswith(f"{prefix}."))
            assert sources == sorted(source.value for source in SourceType)


def test_catalog_index_reads_every_sources_catalog() -> None:
    spec = STAGES["catalog_index"]
    assert sorted(spec.inputs.values()) == sorted(f"data/raw/{s.value}/{CATALOG_FILENAME}" for s in SourceType)
