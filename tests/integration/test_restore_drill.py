"""`scripts/restore_drill.py` (D2 §12) against a scratch tool repo, workspace, DVC remote and bundle folder.

Layout under the test's `tmp_path`:

    parent/energatron-5000/   scratch tool repo: copies of `restore_drill.py` and `privacy_guard.py`, committed
    ws/                       scratch workspace (`_scratch.make_scratch`), with a synthetic `private/` in DVC
    Backups/git/, Backups/dvc/   the bundle folder and the local DVC "remote"
    tmp/                      `$TMPDIR`, where the drill makes its scratch folder
    bin/uv                    a fake `uv`: `sync` does nothing; `run` runs the command from this venv

The drill runs the copy inside the scratch tool repo with `--tool-source local`, so the tool clone comes from the
scratch repo. The backup is made by the real adapter, `GitDvcVersionControl.backup()`. Nothing here touches
iCloud Drive or the real workspace.
"""

import hashlib
import importlib.util
import json
import os
import shutil
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path
from types import ModuleType
from typing import Any

import pytest

from energatron.core.canonical import sha256_hex
from tests.integration._scratch import Scratch, git, make_scratch

pytestmark = pytest.mark.integration

SCRIPTS = Path(__file__).resolve().parents[2] / "scripts"
CONFIG = 'kind = "private_config"\nschema_version = 1\nnmi = "SYNTHNMI0001"\n'
GENERATED = (
    "# energatron denylist v1. Generated by `energatron denylist`; do not edit.\n"
    "# source-sha256: {sha}\n"
    "nmi\tword\tSYNTHNMI0001\n"
)
FAKE_UV = """\
#!{python}
import json, os, sys
args = sys.argv[1:]
with open({log!r}, "a", encoding="utf-8") as f:
    f.write(json.dumps([os.getcwd(), args]) + "\\n")
if args[:1] == ["sync"]:
    sys.exit(0)
if args[:1] == ["run"]:
    rest = args[1:]
    while rest and rest[0].startswith("-"):
        rest = rest[1:]
    exe = os.path.join({bin!r}, rest[0])
    os.execv(exe, [exe, *rest[1:]])
sys.exit(99)
"""


@dataclass
class Drill:
    scratch: Scratch
    tool: Path
    tmpdir: Path
    uv_log: Path
    env: dict[str, str]

    def run(self, *args: str) -> tuple[int, str]:
        done = subprocess.run(
            [sys.executable, str(self.tool / "scripts" / "restore_drill.py"), "--workspace", str(self.scratch.root),
             "--tool-source", "local", *args],
            capture_output=True,
            text=True,
            env=self.env,
            cwd=self.tool.parent,
        )  # fmt: skip
        return done.returncode, done.stdout + done.stderr

    def statuses(self, out: str) -> dict[int, str]:
        """Step number → PASS/FAIL/SKIP, from the text output (`<STATUS>  <n> <name>: <detail>`)."""
        found = {}
        for line in out.splitlines():
            parts = line.split()
            if len(parts) >= 2 and parts[0] in {"PASS", "FAIL", "SKIP"} and parts[1].isdigit():
                found[int(parts[1])] = parts[0]
        return found

    def uv_calls(self) -> list[tuple[str, list[str]]]:
        if not self.uv_log.exists():
            return []
        return [tuple(json.loads(line)) for line in self.uv_log.read_text(encoding="utf-8").splitlines()]  # type: ignore[misc]


def make_tool(parent: Path) -> Path:
    tool = parent / "energatron-5000"
    (tool / "scripts").mkdir(parents=True)
    for name in ("restore_drill.py", "privacy_guard.py"):
        if (SCRIPTS / name).exists():
            shutil.copy2(SCRIPTS / name, tool / "scripts" / name)
    git(tool, "init", "-q", "-b", "main")
    git(tool, "add", "-A")
    git(tool, "commit", "-q", "--allow-empty", "-m", "scratch tool")
    return tool


@pytest.fixture
def drill(tmp_path: Path) -> Drill:
    scratch = make_scratch(tmp_path)
    scratch.write("private/config.toml", CONFIG)
    scratch.write("private/denylist.generated.txt", GENERATED.format(sha=sha256_hex(CONFIG.encode())))
    scratch.write(
        ".energatron/local.toml",
        f'kind = "local_config"\nschema_version = 1\n\n[backup]\nbundle_dir = "{scratch.bundle_dir}"\n',
    )
    scratch.vcs().track(["private"])
    scratch.write("notes.md", "synthetic notes\n")
    scratch.commit_all("scratch workspace")
    scratch.vcs().backup()

    tool = make_tool(tmp_path / "parent")
    tmpdir = tmp_path / "tmp"
    tmpdir.mkdir()
    bin_dir = tmp_path / "bin"
    bin_dir.mkdir()
    uv_log = tmp_path / "uv.log"
    uv = bin_dir / "uv"
    uv.write_text(
        FAKE_UV.format(python=sys.executable, log=str(uv_log), bin=str(Path(sys.executable).parent)),
        encoding="utf-8",
    )
    uv.chmod(0o755)
    env = {**os.environ, "PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}", "TMPDIR": str(tmpdir)}
    return Drill(scratch, tool, tmpdir, uv_log, env)


def no_paths(out: str, *paths: Path) -> bool:
    return not any(str(path) in out for path in paths)


def snapshot(*roots: Path) -> dict[str, tuple[object, ...]]:
    """Every entry under `roots` (the workspace incl. `.git/` and `.dvc/config.local`, the bundle folder and the
    remote): relative path → kind, mode, mtime, size and sha256 (files) or link target (symlinks)."""
    found: dict[str, tuple[object, ...]] = {}
    for root in roots:
        for path in sorted([root, *root.rglob("*")]):
            st = path.lstat()
            key = f"{root.name}/{path.relative_to(root)}"
            if path.is_symlink():
                found[key] = ("link", os.readlink(path))
            elif path.is_dir():
                found[key] = ("dir", st.st_mode, st.st_mtime_ns)
            else:
                digest = hashlib.sha256(path.read_bytes()).hexdigest()
                found[key] = ("file", st.st_mode, st.st_mtime_ns, st.st_size, digest)
    return found


def live_state(drill: Drill) -> dict[str, tuple[object, ...]]:
    """What the drill must never change: the live workspace, the bundle folder and the remote (D2 §12)."""
    assert (drill.scratch.root / ".dvc" / "config.local").is_file()
    return snapshot(drill.scratch.root, drill.scratch.backups)


def test_passes_on_a_fresh_backup(drill: Drill, tmp_path: Path) -> None:
    before = live_state(drill)
    code, out = drill.run("--json")
    assert code == 0, out
    summary: dict[str, Any] = json.loads(out)
    assert summary["ok"] is True
    assert summary["exit_code"] == 0
    steps = {step["step"]: step["status"] for step in summary["steps"]}
    assert sorted(steps) == list(range(1, 13))
    assert steps[4] == "SKIP"  # no code_fingerprint.json before P1
    assert steps[7] == "SKIP"  # no dvc.yaml before P1
    assert steps[9] == "SKIP"  # `energatron verify` doesn't exist yet (P1.3.4)
    assert {steps[n] for n in (1, 2, 3, 5, 6, 8, 10, 11, 12)} == {"PASS"}
    assert summary["counts"]["bundles"] == 1
    assert summary["counts"]["dataless_files"] == 0
    assert no_paths(out, tmp_path)
    assert list(drill.tmpdir.iterdir()) == []  # the scratch folder is gone
    calls = drill.uv_calls()
    assert any(args == ["sync", "--locked"] and Path(cwd).name == "demq-elektric" for cwd, args in calls)
    # In the live workspace uv only reads: no lock update and no venv sync.
    live = [args for cwd, args in calls if Path(cwd) == drill.scratch.root]
    assert live
    assert all(args[:3] == ["run", "--frozen", "--no-sync"] for args in live), live
    assert live_state(drill) == before  # the workspace, bundle folder and remote are unchanged


def test_text_output_and_keep(drill: Drill, tmp_path: Path) -> None:
    code, out = drill.run("--keep")
    assert code == 0, out
    assert drill.statuses(out) == {n: "SKIP" if n in (4, 7, 9, 12) else "PASS" for n in range(1, 13)}
    assert no_paths(out, tmp_path)
    (kept,) = list(drill.tmpdir.iterdir())
    assert kept.name.startswith("energatron-restore-")
    clone = kept / "demq-elektric"
    assert (clone / "private" / "config.toml").read_text(encoding="utf-8") == CONFIG
    assert git(clone, "remote").strip() == ""
    assert (kept / "energatron-5000" / "scripts" / "restore_drill.py").is_file()


def test_fails_at_step_6_after_a_remote_object_is_altered(drill: Drill) -> None:
    digest = hashlib.md5(CONFIG.encode()).hexdigest()  # DVC's content address, not security
    target = drill.scratch.remote_dir / "files" / "md5" / digest[:2] / digest[2:]
    assert target.is_file()
    target.chmod(0o644)
    target.write_bytes(b"altered\n")
    before = live_state(drill)
    code, out = drill.run()
    assert code == 1, out
    statuses = drill.statuses(out)
    assert statuses[6] == "FAIL"
    assert statuses[8] == "PASS"
    assert list(drill.tmpdir.iterdir()) == []
    assert live_state(drill) == before  # `verify true` went to the clone only; the altered object stays


def test_fails_at_step_8_after_a_commit_that_was_not_backed_up(drill: Drill) -> None:
    drill.scratch.write("notes.md", "a newer note\n")
    drill.scratch.commit_all("not backed up")
    code, out = drill.run("--json")
    assert code == 1, out
    summary = json.loads(out)
    steps = {step["step"]: step["status"] for step in summary["steps"]}
    assert steps[8] == "FAIL"
    assert [n for n, status in steps.items() if status == "FAIL"] == [8]
    assert summary["ok"] is False


def test_setup_error_without_local_config_exits_2(drill: Drill) -> None:
    (drill.scratch.root / ".energatron" / "local.toml").unlink()
    code, out = drill.run()
    assert code == 2
    assert drill.statuses(out) == {1: "FAIL"}
    assert list(drill.tmpdir.iterdir()) == []


def test_setup_error_without_a_bundle_exits_2_in_json(drill: Drill) -> None:
    for bundle in drill.scratch.bundle_dir.iterdir():
        bundle.unlink()
    code, out = drill.run("--json")
    assert code == 2
    summary = json.loads(out)
    assert summary["exit_code"] == 2
    assert [(step["step"], step["status"]) for step in summary["steps"]] == [(1, "FAIL")]
    assert no_paths(out, drill.scratch.bundle_dir)


def load_drill() -> ModuleType:
    spec = importlib.util.spec_from_file_location("restore_drill_under_test", SCRIPTS / "restore_drill.py")
    assert spec is not None and spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_an_unexpected_exception_still_gives_one_line_per_step(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch, capsys: pytest.CaptureFixture[str]
) -> None:
    drill = load_drill()
    scratch = tmp_path / "scratch"

    def inputs(self: Any) -> None:
        self.record(1, "PASS", "inputs")

    def make_scratch(self: Any) -> None:
        scratch.mkdir()
        self.scratch = scratch
        self.record(2, "PASS", "scratch")

    def steps(self: Any) -> None:
        for step in (3, 4, 5):
            self.record(step, "PASS", "done")
        raise RuntimeError(str(tmp_path))  # the message may hold a path: never shown

    monkeypatch.setattr(drill.Drill, "inputs", inputs)
    monkeypatch.setattr(drill.Drill, "make_scratch", make_scratch)
    monkeypatch.setattr(drill.Drill, "steps", steps)
    code = drill.main(["--workspace", str(tmp_path / "ws")])
    out = capsys.readouterr().out
    assert code == 1
    lines = [line.split(None, 2) for line in out.splitlines() if line[:4] in {"PASS", "FAIL", "SKIP"}]
    assert [int(n) for _status, n, _rest in lines] == list(range(1, 13))
    statuses = {int(n): status for status, n, _rest in lines}
    assert statuses[6] == "FAIL"
    assert "unexpected RuntimeError" in out
    assert {statuses[n] for n in range(7, 12)} == {"SKIP"}
    assert statuses[12] == "PASS"
    assert not scratch.exists()
    assert str(tmp_path) not in out


def test_remote_url_from_dvc_config() -> None:
    drill = load_drill()
    workspace = Path("/w")
    listing = "remote.a.url=/first\nremote.b.url=/with space/b\ncore.remote=b\n"
    assert drill.remote_url_from(listing, workspace) == "/with space/b"
    assert drill.remote_url_from("remote.only.url=/only\n", workspace) == "/only"
    assert drill.remote_url_from("remote.s.url=s3://bucket/x\n", workspace) == "s3://bucket/x"
    assert drill.remote_url_from("remote.r.url=../../B/dvc\n", workspace) == str(Path("/w/.dvc/../../B/dvc").resolve())
    for listing in ("", "remote.a.url=/a\nremote.b.url=/b\n", "core.remote=missing\n"):
        with pytest.raises(drill.SetupError):
            drill.remote_url_from(listing, workspace)


def test_bundle_dir_must_be_absolute_and_outside_the_workspace(tmp_path: Path) -> None:
    drill = load_drill()
    local = tmp_path / "local.toml"
    for value in ("relative/git", str(tmp_path / "inside")):
        local.write_text(f'[backup]\nbundle_dir = "{value}"\n', encoding="utf-8")
        with pytest.raises(drill.SetupError) as raised:
            drill.bundle_dir_from(local, tmp_path)
        assert str(tmp_path) not in str(raised.value)
    local.write_text('[backup]\nbundle_dir = "~/elsewhere"\n', encoding="utf-8")
    assert drill.bundle_dir_from(local, tmp_path) == Path.home() / "elsewhere"
