"""`adapters/sources/pdf_text.py`: a PDF's kind and issue date from its text (bill PDF spec §2, §3).

Every PDF is generated by `make_pdf`; every text is synthetic.
"""

from datetime import datetime

import pytest

from energatron.adapters.sources.pdf_text import issue_date, pdf_kind, pdf_text
from energatron.core.models.catalog import SourceType
from tests.fixtures.make_sources import make_pdf

ELEC_TEXT = ("Tax invoice", "Issue date 23 Jan 2025", "National Metering Identifier (NMI) <NMI>",
             "Here is your electricity bill")  # fmt: skip
GAS_TEXT = ("Here is your monthly gas bill", "Issue date", "27 Oct 2026", "Number (MIRN) <MIRN>", "Tax Invoice")
SUMMARY_TEXT = ("NMI: <NMI>", "Data Meter Summary Format", "General Supply")


def test_the_text_of_a_generated_pdf_comes_back_line_by_line() -> None:
    assert pdf_text(make_pdf(creation_date=None, text=ELEC_TEXT)).splitlines() == list(ELEC_TEXT)


def test_a_pdf_with_no_text_or_pypdf_cannot_read_has_none() -> None:
    assert pdf_text(make_pdf(creation_date="D:2025")).strip() in {"", "Synthetic test page"}
    assert pdf_text(b"%PDF-1.4\nnot really a pdf\n%%EOF\n") == ""
    assert pdf_text(b"") == ""


@pytest.mark.parametrize(
    ("text", "kind"),
    [
        (ELEC_TEXT, SourceType.ELEC_BILL),
        (GAS_TEXT, SourceType.GAS_BILL),
        (SUMMARY_TEXT, SourceType.SAPN_SUMMARY),
        (("Your electricity bill", "Issue date 1 May 2025"), SourceType.ELEC_BILL),
        (("Tax invoice", "Meter Installation Registration Number <MIRN>"), SourceType.GAS_BILL),
        (("Tax invoice", "NMI <NMI>", "MIRN <MIRN>"), None),  # dual fuel: both, so neither
        (("NMI <NMI>",), None),  # names a meter but isn't a bill or a summary
        (("Meter summary", "Tax invoice", "NMI <NMI>"), SourceType.ELEC_BILL),  # a bill that mentions a summary
        (("Greenhouse gas emissions", "Tax invoice", "NMI <NMI>"), SourceType.ELEC_BILL),
        ((), None),
    ],
)
def test_the_kind_a_text_names(text: tuple[str, ...], kind: SourceType | None) -> None:
    assert pdf_kind("\n".join(text)) is kind


@pytest.mark.parametrize(
    ("text", "expected"),
    [
        ("Issue date 23 Jan 2025", datetime(2025, 1, 23)),
        ("Issue date\n27 Oct 2026", datetime(2026, 10, 27)),
        ("ISSUE DATE: 3 September 2025", datetime(2025, 9, 3)),
        ("Issue date 3 Sept 2025", datetime(2025, 9, 3)),
        ("Date of issue: 1st May, 2025", datetime(2025, 5, 1)),
        ("Date issued 09/04/2025", datetime(2025, 4, 9)),  # day first
        ("Issued on 2025-04-09", datetime(2025, 4, 9)),
        ("Due date 30 Jan 2025\nIssue date 23 Jan 2025", datetime(2025, 1, 23)),  # only after an issue label
        ("Issue date 31 Feb 2025\nIssue date 1 Mar 2025", datetime(2025, 3, 1)),  # an impossible date is skipped
        ("Issue date 17 Foo 2025", None),
        ("Issue date to follow", None),
        ("Due date 30 Jan 2025", None),
        ("", None),
    ],
)
def test_the_issue_date(text: str, expected: datetime | None) -> None:
    assert issue_date(text) == expected


def test_the_first_issue_label_wins_whatever_its_format() -> None:
    assert issue_date("Issue date 2025-02-01\nIssue date 5 Jan 2025") == datetime(2025, 2, 1)
