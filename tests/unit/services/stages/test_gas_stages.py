def bills_summary(root: Path) -> GasBillsSummary:
    return GasBillsSummary.from_document(json.loads((root / BILLS_OUT / "summary.json").read_bytes()))


def profile_summary(root: Path) -> GasProfileSummary:
    return GasProfileSummary.from_document(json.loads((root / PROFILE_OUT / "summary.json").read_bytes()))


def land_record(root: Path, document: dict[str, Any], name: str = "extra.yaml") -> str:
    return land_blob(root, SourceType.GAS_BILL_RECORD, name, gas.record_bytes(document), landed_at=LATER).dataset_id


def land_pdf(root: Path, month: int) -> str:
    pdf = make_pdf(creation_date=f"D:2026{month:02d}05120000Z")
    return land_blob(root, SourceType.GAS_BILL, f"x-{month}.pdf", pdf).dataset_id


def land_unreadable_record(root: Path) -> None:
    """A catalogued record whose blob no longer validates (as after a schema change): a valid record's catalog line
    with the blob and hash of a stub."""
    valid = make_record(SourceType.GAS_BILL_RECORD, "y.yaml", gas.record_bytes(gas.record()), landed_at=LATER)
    stub = b"kind: gas_bill_record\nschema_version: 1\n"
    digest = sha256_hex(stub)
    ident = dataset_id(SourceType.GAS_BILL_RECORD.value, valid.source_ts, digest)
    record = valid.model_copy(
        update={
            "dataset_id": ident,
            "sha256": digest,
            "bytes": len(stub),
            "stored_path": blob_key(SourceType.GAS_BILL_RECORD, ident, ".yaml"),
        }
    )
    (root / record.stored_path).parent.mkdir(parents=True, exist_ok=True)
    (root / record.stored_path).write_bytes(stub)
    catalog = root / "data/raw/gas_bill_record/_catalog.jsonl"
    catalog.write_bytes(catalog.read_bytes() + canonical_json(record.model_dump(mode="json")) + b"\n")


# gas_bills


def test_every_check_passes_and_the_newest_record_per_pdf_is_current(zone: GasZone, root: Path) -> None:
    result = run(root, "gas_bills")
    assert [check.name for check in result.checks] == BILL_CHECKS
    assert passed(result)
    summary = bills_summary(root)
    assert (summary.records, summary.current, summary.superseded) == (4, 3, 1)
    assert (summary.first_period_start, summary.last_period_end) == (date(2026, 8, 1), date(2026, 10, 31))
    bills = pq.read_table(root / BILLS_OUT / "bills.parquet").to_pylist()
    assert [row["record_dataset_id"] for row in bills] == list(zone.records)
    assert [row["end_read_type"] for row in bills] == ["actual", "estimate", "actual"]
    assert all(row["recomputed_total"] == row["total"] for row in bills)
    reads = pq.read_table(root / BILLS_OUT / "reads.parquet").to_pylist()
    assert len(reads) == 4
    assert all(row["recomputed_mj"] == row["mj"] for row in reads)
    lines = pq.read_table(root / BILLS_OUT / "lines.parquet").to_pylist()
    assert {row["line"] for row in lines} == {"usage", "supply"}


