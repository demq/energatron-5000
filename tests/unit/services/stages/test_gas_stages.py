# gas_profile


@pytest.mark.usefixtures("zone")
def test_the_profile_combines_the_estimate_and_takes_the_reference(root: Path) -> None:
    run(root, "gas_bills")
    result = run(root, "gas_profile")
    assert passed(result)
    assert list(result.warnings) == []
    periods = pq.read_table(root / PROFILE_OUT / "periods.parquet").to_pylist()
    assert [(row["period_start"], row["period_end"], row["bills"], row["estimated"]) for row in periods] == [
        (date(2026, 8, 1), date(2026, 8, 31), 1, False),
        (date(2026, 9, 1), date(2026, 10, 31), 2, False),
    ]
    assert all(row["in_reference"] for row in periods)
    summary = profile_summary(root)
    assert (summary.reference_days, summary.reference_bills, summary.partial_year) == (92, 3, True)
    bills = pq.read_table(root / BILLS_OUT / "bills.parquet").to_pylist()
    assert summary.reference_mj == sum((row["mj"] for row in bills), Decimal(0))
    months = pq.read_table(root / PROFILE_OUT / "monthly.parquet").to_pylist()
    assert [(row["month"], row["days_covered"]) for row in months] == [
        ("2026-08", 31),
        ("2026-09", 30),
        ("2026-10", 31),
    ]


