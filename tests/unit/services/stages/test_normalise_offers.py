CHECKS = [
    "blobs_match_catalog",
    "detector_known",
    "snapshot_ids_recompute",
    "rules_valid",
    "every_offer_accounted",
    "tariffs_partition",
]


def _code() -> StageCode:
    source = sha256_hex(b"normalise_offers")
    digest = content_hash({"source_sha256": source, "packages": {}, "python": "3.14.0"})
    return StageCode(stage_sha256=digest, source_sha256=source, python="3.14.0", packages={}, files=["__init__.py"])


def normalise(root: Path) -> StageResult:
    spec = get_stage("normalise_offers")
    prepared = prepare_stage(spec, root=root, params_file=root / "params.yaml")
    code = _code()
    return run_stage(
        spec, prepared.inputs, prepared.params, prepared.outputs, code=code, recorded_code=code.stage_sha256
    )


@pytest.fixture(scope="module")
def template(tmp_path_factory: pytest.TempPathFactory) -> OfferZone:
    root = tmp_path_factory.mktemp("offers")
    empty_raw_zone(root)
    (root / "params.yaml").write_text(params_v5_text(region=True))
    return build_offer_zone(root)


@pytest.fixture
def zone(template: OfferZone, tmp_path: Path) -> OfferZone:
    root = tmp_path / "workspace"
    shutil.copytree(template.root, root)
    return replace(template, root=root)


def out(root: Path) -> Path:
    return root / "data" / "marts" / "offers"


def rows(root: Path) -> dict[str, dict[str, Any]]:
    return {row["plan_id"]: row for row in pq.read_table(out(root) / "offers.parquet").to_pylist()}


def tariffs(root: Path) -> OfferTariffs:
    return OfferTariffs.from_document(json.loads((out(root) / "tariffs.json").read_text()))


def summary(root: Path) -> OffersSummary:
    return OffersSummary.from_document(json.loads((out(root) / "summary.json").read_text()))


def failed_checks(root: Path) -> list[str]:
    with pytest.raises(CheckFailedError):
        normalise(root)
    provenance = json.loads((out(root) / "_provenance.json").read_text())
    return [check["name"] for check in provenance["checks"] if check["status"] == "fail"]


# The fixture zone


def test_every_check_passes_on_the_fixture_zone(zone: OfferZone) -> None:
    result = normalise(zone.root)
    assert [check.name for check in result.checks] == CHECKS
    assert all(check.status == "pass" for check in result.checks)
    assert result.warnings == []


def test_the_current_plans_and_the_manual_offer_are_considered_once_each(zone: OfferZone) -> None:
    normalise(zone.root)
    found = rows(zone.root)
    assert sorted(found) == sorted([*CURRENT_CDR, MANUAL_ID])
    assert GONE_ID not in found  # only the older fetch log lists it
    assert found[CL_ID]["status"] == "excluded"
    assert found[CL_ID]["reasons"] == ["controlled_load_plan"]
    assert (found[TOU_ID]["status"], found[FLAT_ID]["status"], found[BETA_ID]["status"]) == ("normalised",) * 3
    assert (found[BETA_ID]["retailer"], found[BETA_ID]["brand"]) == ("beta-energy", "beta")
    assert (found[MANUAL_ID]["source"], found[MANUAL_ID]["retailer"]) == ("manual", "manual")


def test_the_newest_snapshot_of_a_plan_is_the_one_priced(zone: OfferZone) -> None:
    normalise(zone.root)
    (tou,) = [found for found in tariffs(zone.root).tariffs if found.plan_id == TOU_ID]
    assert tou.offer_snapshot_id == rows(zone.root)[TOU_ID]["offer_snapshot_id"]
    peak = next(charge for charge in tou.seasons[0].energy if charge.label == "PEAK")
    assert str(peak.blocks[0].unit_price) == "0.40"  # the newer snapshot's, not the older 0.45


def test_tariffs_hold_the_priced_offers_and_the_as_of_date(zone: OfferZone) -> None:
    normalise(zone.root)
    found = tariffs(zone.root)
    assert str(found.as_of) == "2026-11-01"
    assert [tariff.plan_id for tariff in found.tariffs] == sorted(
        [FLAT_ID, TOU_ID, BETA_ID, MANUAL_ID], key=lambda plan: rows(zone.root)[plan]["offer_snapshot_id"]
    )
    manual = next(tariff for tariff in found.tariffs if tariff.plan_id == MANUAL_ID)
    assert str(manual.seasons[0].daily_supply) == "1"  # written as 1.10 with GST


def test_the_summary_counts_statuses_reasons_and_batches(zone: OfferZone) -> None:
    normalise(zone.root)
    found = summary(zone.root)
    assert found.statuses == {"normalised": 4, "approximate": 0, "excluded": 1}
    assert found.reasons == {"controlled_load_plan": 1}
    assert (found.current_plans, found.missing_snapshot, found.manual) == (4, 0, 1)
    assert found.batches == {"alpha": "fetch-20261101T000000Z", "beta-energy": "fetch-20261101T000000Z"}
    assert found.retailers["alpha"].excluded == 1
    assert all(found.checks.values())


def test_the_outputs_are_byte_identical_on_a_rerun(zone: OfferZone) -> None:
    normalise(zone.root)
    first = {path.name: path.read_bytes() for path in out(zone.root).iterdir()}
    normalise(zone.root)
    assert {path.name: path.read_bytes() for path in out(zone.root).iterdir()} == first


def test_no_offer_data_gives_empty_outputs(tmp_path: Path) -> None:
    empty_raw_zone(tmp_path)
    (tmp_path / "params.yaml").write_text(params_v5_text(region=True))
    normalise(tmp_path)
    assert rows(tmp_path) == {}
    assert tariffs(tmp_path).as_of is None


# Rules and params


def test_a_local_rule_applies(zone: OfferZone) -> None:
    rule = {
        "kind": "offer_rule",
        "schema_version": 1,
        "id": "beta-closed",
        "description": "Made up.",
        "match": {"brand": "beta"},
        "effect": {"exclude": "closed_to_new_customers"},
        "verified_on": "2026-11-01",
        "cites": [],
    }
    (zone.root / "config" / "offer_rules.local" / "beta.yaml").write_text(json.dumps(rule))
    normalise(zone.root)
    found = rows(zone.root)[BETA_ID]
    assert (found["status"], found["reasons"], found["rules"]) == (
        "excluded",
        ["rule:beta-closed:closed_to_new_customers"],
        ["beta-closed"],
    )


def test_an_invalid_local_rule_fails_rules_valid(zone: OfferZone) -> None:
    (zone.root / "config" / "offer_rules.local" / "bad.yaml").write_text("kind: [unclosed\n")
    assert failed_checks(zone.root) == ["rules_valid"]


def test_a_household_with_controlled_load_keeps_the_controlled_load_variant(zone: OfferZone) -> None:
    (zone.root / "params.yaml").write_text(params_v5_text(region=True, controlled_load=True))
    normalise(zone.root)
    assert rows(zone.root)[CL_ID]["status"] == "normalised"


def test_null_retailers_are_invalid_input(zone: OfferZone) -> None:
    (zone.root / "params.yaml").write_text(params_v5_text(region=False))
    with pytest.raises(InvalidInputError):
        normalise(zone.root)


# Failing checks


def test_a_tampered_blob_fails_blobs_match_catalog(zone: OfferZone) -> None:
    (zone.root / zone.plans[FLAT_ID].stored_path).write_bytes(b"{}")
    assert failed_checks(zone.root) == ["blobs_match_catalog"]
    assert FLAT_ID not in rows(zone.root)  # left out: the plan is current but has no readable snapshot
    assert summary(zone.root).missing_snapshot == 1


def test_an_unknown_detector_version_fails_detector_known(zone: OfferZone) -> None:
    catalog = zone.root / "data" / "raw" / "offer_manual" / "_catalog.jsonl"
    record = json.loads(catalog.read_text())
    record["detector"]["version"] = 99
    catalog.write_bytes(canonical_json(record) + b"\n")
    failed = failed_checks(zone.root)
    assert failed == ["detector_known"]


def test_a_recorded_snapshot_id_that_does_not_recompute_fails(zone: OfferZone) -> None:
    catalog = zone.root / "data" / "raw" / "offer_cdr" / "_catalog.jsonl"
    lines = [json.loads(line) for line in catalog.read_text().splitlines()]
    for line in lines:
        if line["extra"]["plan_id"] == BETA_ID:
            line["extra"]["offer_snapshot_id"] = "TEST-B@EME~20200101T000000Z~00000000"
    catalog.write_bytes(b"".join(canonical_json(line) + b"\n" for line in lines))
    assert failed_checks(zone.root) == ["snapshot_ids_recompute"]


def test_a_current_plan_without_a_snapshot_warns(zone: OfferZone) -> None:
    log = cdr.fetch_log(
        batch="fetch-20261102T000000Z",
        fetched_at="2026-11-02T00:00:00Z",
        retailers=[("alpha", [])],
        selected=[cdr.selected("NEVER-LANDED@EME")],
    )
    land_blob(zone.root, SourceType.OFFER_CDR_INDEX, "fetch-log-3.json", cdr.fetch_log_body(log))
    result = normalise(zone.root)
    assert [warning.code for warning in result.warnings] == [WarningCode.W_OFFERS_MISSING_SNAPSHOT]
    assert summary(zone.root).missing_snapshot == 1
    assert FLAT_ID not in rows(zone.root)  # the newest alpha log no longer lists it
    assert BETA_ID in rows(zone.root)  # beta's newest log is still the earlier one


def test_a_base_whose_list_failed_keeps_its_previous_current_plans(zone: OfferZone) -> None:
    log = cdr.fetch_log(batch="fetch-20261102T000000Z", fetched_at="2026-11-02T00:00:00Z", retailers=[("alpha", [])])
    log["retailers"][0] |= {"pages": [], "error": {"code": "E_NETWORK", "message": "down", "status": 503}}
    land_blob(zone.root, SourceType.OFFER_CDR_INDEX, "fetch-log-3.json", cdr.fetch_log_body(log))
    normalise(zone.root)
    assert FLAT_ID in rows(zone.root)
