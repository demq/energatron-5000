"""The `normalise_offers` stage (P4 spec §8): current plans, newest snapshots, rules, the three outputs and six checks.

The workspace is `empty_raw_zone` plus `build_offer_zone`; every plan is generated by `tests/fixtures/make_cdr.py`.
"""

