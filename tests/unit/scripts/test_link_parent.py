"""`scripts/link_parent.py` (D2 §10.2): command wrappers, skill links and the three parent-folder symlinks.

Every test runs the real script as a subprocess with `--parent-dir` pointing at a scratch parent folder, so the
real `~/WorkSpace/Electricity/` is never read or written.
"""

import json
import os
import subprocess
import sys
from dataclasses import dataclass
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parents[3] / "scripts" / "link_parent.py"
SKILL = "---\nname: {name}\ndescription: {description}\n---\n\n# {name}\n"
SETTINGS = {"permissions": {"deny": ["Read(./private/**)"]}}

# The parent-folder links and their expected targets (D2 §10.2), for a tool repo called `tool`.
PARENT_LINKS = {
    "CLAUDE.md": "tool/parent/CLAUDE.md",
    "AGENTS.md": "CLAUDE.md",
    ".claude/settings.json": "../tool/.claude/settings.json",
}


@dataclass
class Ran:
    code: int
    out: str
    err: str


def run(parent: Path, *args: str) -> Ran:
    done = subprocess.run(
        [sys.executable, str(SCRIPT), "--parent-dir", str(parent), *args], capture_output=True, text=True
    )
    return Ran(done.returncode, done.stdout, done.stderr)


def add_skill(repo: Path, name: str, description: str = "Does a thing.") -> None:
    skill = repo / ".claude" / "skills" / name
    skill.mkdir(parents=True)
    (skill / "SKILL.md").write_text(SKILL.format(name=name, description=description), encoding="utf-8")


def add_parent_dir(repo: Path) -> None:
    (repo / "parent").mkdir()
    (repo / "parent" / "CLAUDE.md").write_text("# parent\n\nRules.\n", encoding="utf-8")
    (repo / ".claude").mkdir(exist_ok=True)
    (repo / ".claude" / "settings.json").write_text(json.dumps(SETTINGS), encoding="utf-8")


def snapshot(root: Path) -> dict[str, str]:
    """Every path under root, with a symlink's target or a file's text, to prove that nothing changed."""
    state: dict[str, str] = {}
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root).as_posix()
        if path.is_symlink():
            state[rel] = "-> " + os.readlink(path)
        elif path.is_file():
            state[rel] = path.read_text(encoding="utf-8")
        else:
            state[rel] = "dir"
    return state


@pytest.fixture
def parent(tmp_path: Path) -> Path:
    """A scratch parent folder holding a tool repo with two skills and a `parent/` directory, and a workspace."""
    root = tmp_path / "parent"
    tool = root / "tool"
    add_skill(tool, "next")
    add_skill(tool, "done")
    add_parent_dir(tool)
    add_skill(root / "workspace", "land")
    return root


def test_create_writes_wrappers_skill_links_and_parent_links(parent: Path) -> None:
    ran = run(parent)
    assert ran.code == 0, ran.err
    for name, repo in (("next", "tool"), ("done", "tool"), ("land", "workspace")):
        wrapper = (parent / ".claude" / "commands" / f"{name}.md").read_text(encoding="utf-8")
        assert "Generated by energatron-5000/scripts/link_parent.py" in wrapper
        assert f"`{repo}/.claude/skills/{name}/SKILL.md`" in wrapper
        assert os.readlink(parent / ".agents" / "skills" / name) == f"../../{repo}/.claude/skills/{name}"
    for rel, target in PARENT_LINKS.items():
        assert os.readlink(parent / rel) == target
    assert (parent / "CLAUDE.md").read_text(encoding="utf-8") == "# parent\n\nRules.\n"
    assert (parent / "AGENTS.md").read_text(encoding="utf-8") == "# parent\n\nRules.\n"
    assert json.loads((parent / ".claude" / "settings.json").read_text(encoding="utf-8")) == SETTINGS


def test_up_to_date_run_changes_nothing_and_check_passes(parent: Path) -> None:
    assert run(parent).code == 0
    before = snapshot(parent)
    ran = run(parent)
    assert ran.code == 0
    assert "up to date" in ran.out
    assert snapshot(parent) == before
    assert run(parent, "--check").code == 0


def test_check_reports_missing_parent_links_and_writes_nothing(parent: Path) -> None:
    before = snapshot(parent)
    ran = run(parent, "--check")
    assert ran.code == 1
    for rel in PARENT_LINKS:
        assert f"out of date (link): {rel}" in ran.out
    assert snapshot(parent) == before


# Links this script would have made for a repo called `old` (e.g. after a rename): relinked, since they're ours.
OLD_REPO_LINKS = {"CLAUDE.md": "old/parent/CLAUDE.md", ".claude/settings.json": "../old/.claude/settings.json"}


@pytest.mark.parametrize("rel", list(OLD_REPO_LINKS))
def test_parent_link_to_another_repo_is_relinked(parent: Path, rel: str) -> None:
    assert run(parent).code == 0
    link = parent / rel
    link.unlink()
    link.symlink_to(OLD_REPO_LINKS[rel])
    check = run(parent, "--check")
    assert check.code == 1
    assert f"out of date (relink): {rel}" in check.out
    assert run(parent).code == 0
    assert os.readlink(link) == PARENT_LINKS[rel]
    assert run(parent, "--check").code == 0


@pytest.mark.parametrize("rel", list(PARENT_LINKS))
def test_foreign_file_is_left_alone_and_reported(parent: Path, rel: str) -> None:
    foreign = parent / rel
    foreign.parent.mkdir(parents=True, exist_ok=True)
    foreign.write_text("hand-written\n", encoding="utf-8")
    ran = run(parent)
    assert ran.code == 1
    assert f"problem: {rel} is not the expected symlink; move it away" in ran.err
    assert not foreign.is_symlink()
    assert foreign.read_text(encoding="utf-8") == "hand-written\n"
    assert run(parent, "--check").code == 1


@pytest.mark.parametrize("rel", ["somewhere-else.md", "../elsewhere/settings.json", "tool/README.md"])
def test_foreign_symlink_is_left_alone_and_reported(parent: Path, rel: str) -> None:
    for name in PARENT_LINKS:
        link = parent / name
        link.parent.mkdir(parents=True, exist_ok=True)
        link.symlink_to(rel)
    ran = run(parent)
    assert ran.code == 1
    for name in PARENT_LINKS:
        assert f"problem: {name} is a symlink this script didn't make; move it away" in ran.err
        assert os.readlink(parent / name) == rel
    assert run(parent, "--check").code == 1


def test_missing_source_file_is_a_problem(parent: Path) -> None:
    (parent / "tool" / ".claude" / "settings.json").unlink()
    ran = run(parent)
    assert ran.code == 1
    assert "problem: tool/.claude/settings.json is missing" in ran.err
    assert not (parent / ".claude" / "settings.json").is_symlink()
    assert run(parent, "--check").code == 1


def test_missing_parent_claude_md_skips_agents_md_too(parent: Path) -> None:
    (parent / "tool" / "parent" / "CLAUDE.md").unlink()
    ran = run(parent)
    assert ran.code == 1
    assert "problem: tool/parent/CLAUDE.md is missing" in ran.err
    assert not (parent / "CLAUDE.md").is_symlink()
    assert not (parent / "AGENTS.md").is_symlink()
    assert os.readlink(parent / ".claude" / "settings.json") == PARENT_LINKS[".claude/settings.json"]
    check = run(parent, "--check")
    assert check.code == 1
    assert "AGENTS.md" not in check.out


def test_two_repos_with_a_parent_directory_is_an_error(parent: Path) -> None:
    add_parent_dir(parent / "workspace")
    before = snapshot(parent)
    ran = run(parent)
    assert ran.code != 0
    assert "parent/" in ran.err
    assert "tool" in ran.err and "workspace" in ran.err
    assert snapshot(parent) == before


def test_parent_links_are_stale_once_parent_dir_is_gone_and_prune_removes_them(parent: Path) -> None:
    assert run(parent).code == 0
    for path in sorted((parent / "tool" / "parent").iterdir()):
        path.unlink()
    (parent / "tool" / "parent").rmdir()

    check = run(parent, "--check")
    assert check.code == 1
    for rel in PARENT_LINKS:
        assert f"out of date (stale): {rel}" in check.out

    kept = run(parent)
    assert kept.code == 0
    for rel in PARENT_LINKS:
        assert f"stale, kept (use --prune to remove): {rel}" in kept.out
        assert (parent / rel).is_symlink()

    pruned = run(parent, "--prune")
    assert pruned.code == 0
    for rel in PARENT_LINKS:
        assert not (parent / rel).is_symlink()
        assert not (parent / rel).exists()
    assert run(parent, "--check").code == 0


def test_prune_leaves_foreign_parent_files_alone(parent: Path) -> None:
    (parent / "tool" / "parent" / "CLAUDE.md").unlink()
    (parent / "tool" / "parent").rmdir()
    (parent / "CLAUDE.md").write_text("hand-written\n", encoding="utf-8")
    (parent / "AGENTS.md").symlink_to("README.md")
    ran = run(parent, "--prune")
    assert ran.code == 0
    assert (parent / "CLAUDE.md").read_text(encoding="utf-8") == "hand-written\n"
    assert os.readlink(parent / "AGENTS.md") == "README.md"


def test_stale_skill_entries_are_pruned(parent: Path) -> None:
    assert run(parent).code == 0
    skill = parent / "workspace" / ".claude" / "skills" / "land"
    (skill / "SKILL.md").unlink()
    skill.rmdir()
    assert run(parent, "--check").code == 1
    assert run(parent, "--prune").code == 0
    assert not (parent / ".claude" / "commands" / "land.md").exists()
    assert not (parent / ".agents" / "skills" / "land").is_symlink()
    assert run(parent, "--check").code == 0


def test_foreign_command_file_is_left_alone(parent: Path) -> None:
    commands = parent / ".claude" / "commands"
    commands.mkdir(parents=True)
    (commands / "next.md").write_text("mine\n", encoding="utf-8")
    ran = run(parent)
    assert ran.code == 1
    assert "was not generated by this script" in ran.err
    assert (commands / "next.md").read_text(encoding="utf-8") == "mine\n"


def test_without_a_parent_dir_repo_no_parent_links_are_made(tmp_path: Path) -> None:
    root = tmp_path / "parent"
    add_skill(root / "tool", "next")
    ran = run(root)
    assert ran.code == 0, ran.err
    for rel in PARENT_LINKS:
        assert not (root / rel).is_symlink()
    assert run(root, "--check").code == 0
