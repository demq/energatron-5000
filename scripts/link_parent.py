#!/usr/bin/env python3
"""Expose the repos' agent skills to sessions started in the parent folder.

Agent sessions start in the folder that holds energatron-5000 and the workspace. That folder is not a git repo
and must never become one, so nothing in it is hand-written: this script generates it from the skills inside
the sibling repos, which stay the only source of truth (and are what gets backed up).

For every <repo>/.claude/skills/<name>/SKILL.md directly under the parent folder, it maintains:
  <parent>/.claude/commands/<name>.md  a wrapper telling Claude Code to follow the skill. It's a generated copy,
                                       not a symlink, because symlinked command files may not be discovered.
  <parent>/.agents/skills/<name>       a relative symlink to the skill directory, which Codex follows

From the one repo that has a `parent/` directory (D2 §10.2; more than one is an error), it also maintains:
  <parent>/CLAUDE.md                   -> <repo>/parent/CLAUDE.md
  <parent>/AGENTS.md                   -> CLAUDE.md
  <parent>/.claude/settings.json       -> ../<repo>/.claude/settings.json

A path that exists and isn't what this script makes (a file, or a symlink pointing elsewhere) is reported as
a problem and never overwritten. A parent link whose repo source is missing is skipped, with AGENTS.md too
when it's CLAUDE.md's, so no link dangles.

Usage:  python3 energatron-5000/scripts/link_parent.py [--check] [--prune]
  --check  report what is out of date and exit 1 if anything is; write nothing
  --prune  also remove generated wrappers and links whose source no longer exists
  --parent-dir DIR  use DIR as the parent folder instead of this script's grandparent (tests only)

Stdlib only, so it runs before any venv exists.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path

MARKER = "Generated by energatron-5000/scripts/link_parent.py"
PARENT = Path(__file__).resolve().parents[2]

# The parent folder's fixed symlinks (D2 §10.2), for a repo called {repo}: link path -> target.
PARENT_LINKS = {
    "CLAUDE.md": "{repo}/parent/CLAUDE.md",
    "AGENTS.md": "CLAUDE.md",
    ".claude/settings.json": "../{repo}/.claude/settings.json",
}
# What each link needs to exist in the repo; AGENTS.md points at the parent's own CLAUDE.md link.
PARENT_SOURCES = {"CLAUDE.md": "parent/CLAUDE.md", ".claude/settings.json": ".claude/settings.json"}
# Links that would dangle without another parent link: skipped whenever that one is.
PARENT_NEEDS = {"AGENTS.md": "CLAUDE.md"}


def frontmatter(skill_md: Path) -> dict[str, str]:
    """Top-level `key: value` pairs of a SKILL.md frontmatter (our skills only use single-line values)."""
    lines = skill_md.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        sys.exit(f"{skill_md}: no frontmatter")
    fields: dict[str, str] = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return fields
        key, sep, value = line.partition(":")
        if sep and not line[:1].isspace():
            fields[key.strip()] = value.strip().strip("\"'")
    sys.exit(f"{skill_md}: unterminated frontmatter")


def find_skills(parent: Path) -> dict[str, Path]:
    skills: dict[str, Path] = {}
    for skill_md in sorted(parent.glob("*/.claude/skills/*/SKILL.md")):
        name = skill_md.parent.name
        if name in skills:
            sys.exit(f"skill {name!r} exists in two repos: {skills[name]} and {skill_md.parent}")
        skills[name] = skill_md.parent
    return skills


def find_parent_repo(parent: Path) -> Path | None:
    """The one repo directly under the parent folder that has a `parent/` directory, or None."""
    repos = sorted(p.parent for p in parent.glob("*/parent") if p.is_dir() and not p.is_symlink())
    if len(repos) > 1:
        names = ", ".join(repo.name for repo in repos)
        sys.exit(f"more than one repo has a parent/ directory: {names}; keep exactly one")
    return repos[0] if repos else None


def wrapper(parent: Path, skill_dir: Path) -> str:
    fm = frontmatter(skill_dir / "SKILL.md")
    rel = skill_dir.relative_to(parent).as_posix()
    # JSON strings are valid YAML double-quoted scalars, so any description survives intact.
    lines = ["---", f"description: {json.dumps(fm.get('description', skill_dir.name), ensure_ascii=False)}"]
    if "argument-hint" in fm:
        lines.append(f"argument-hint: {json.dumps(fm['argument-hint'], ensure_ascii=False)}")
    if fm.get("disable-model-invocation") == "true":
        lines.append("disable-model-invocation: true")
    lines += [
        "---",
        f"<!-- {MARKER} from {rel}/SKILL.md. Edit the skill, then re-run the script. -->",
        f"Read `{rel}/SKILL.md` and follow it exactly. Arguments: $ARGUMENTS",
    ]
    return "\n".join(lines) + "\n"


def is_generated(path: Path) -> bool:
    return path.is_file() and not path.is_symlink() and MARKER in path.read_text(encoding="utf-8")


def is_skill_link(path: Path) -> bool:
    return path.is_symlink() and "/.claude/skills/" in "/" + os.readlink(path)


def is_parent_link(path: Path, rel: str) -> bool:
    """A symlink at one of the PARENT_LINKS paths that points where this script would point it, for any repo."""
    if not path.is_symlink():
        return False
    pattern = PARENT_LINKS[rel].split("{repo}")
    target = os.readlink(path)
    if len(pattern) == 1:
        return target == pattern[0]
    head, tail = pattern
    repo = target[len(head) : len(target) - len(tail)] if target.startswith(head) and target.endswith(tail) else ""
    return bool(repo) and "/" not in repo and repo not in (".", "..")


Change = tuple[str, Path, str]


def plan_parent_links(parent: Path, repo: Path | None) -> tuple[list[Change], list[str]]:
    changes: list[Change] = []
    problems: list[str] = []
    if repo is None:
        changes += [("stale", parent / rel, "") for rel in PARENT_LINKS if is_parent_link(parent / rel, rel)]
        return changes, problems
    skipped: set[str] = set()
    for rel, template in PARENT_LINKS.items():
        source = PARENT_SOURCES.get(rel)
        if source is not None and not (repo / source).is_file():
            problems.append(f"{(repo / source).relative_to(parent).as_posix()} is missing")
            skipped.add(rel)
            continue
        if PARENT_NEEDS.get(rel) in skipped:
            skipped.add(rel)
            continue
        link = parent / rel
        target = template.format(repo=repo.name)
        if link.is_symlink():
            if not is_parent_link(link, rel):
                problems.append(f"{rel} is a symlink this script didn't make; move it away")
            elif os.readlink(link) != target:
                changes.append(("relink", link, target))
        elif link.exists():
            problems.append(f"{rel} is not the expected symlink; move it away")
        else:
            changes.append(("link", link, target))
    return changes, problems


def plan(parent: Path, skills: dict[str, Path]) -> tuple[list[Change], list[str]]:
    commands = parent / ".claude" / "commands"
    links = parent / ".agents" / "skills"
    changes: list[Change] = []
    problems: list[str] = []
    for name, skill_dir in skills.items():
        cmd = commands / f"{name}.md"
        want = wrapper(parent, skill_dir)
        if cmd.is_symlink() or (cmd.exists() and not is_generated(cmd)):
            problems.append(f"{cmd.relative_to(parent).as_posix()} was not generated by this script; move it away")
        elif not cmd.exists() or cmd.read_text(encoding="utf-8") != want:
            changes.append(("write", cmd, want))

        link = links / name
        target = os.path.relpath(skill_dir, links)
        if link.is_symlink():
            if os.readlink(link) != target:
                changes.append(("relink", link, target))
        elif link.exists():
            problems.append(f"{link.relative_to(parent).as_posix()} is not a symlink; move it away")
        else:
            changes.append(("link", link, target))

    stale_cmds = [p for p in sorted(commands.glob("*.md")) if p.stem not in skills and is_generated(p)]
    stale_links = [p for p in sorted(links.glob("*")) if p.name not in skills and is_skill_link(p)]
    changes += [("stale", p, "") for p in stale_cmds + stale_links]

    link_changes, link_problems = plan_parent_links(parent, find_parent_repo(parent))
    return changes + link_changes, problems + link_problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0] if __doc__ else None)
    parser.add_argument("--check", action="store_true", help="report only; exit 1 if anything is out of date")
    parser.add_argument("--prune", action="store_true", help="remove generated entries whose source is gone")
    parser.add_argument("--parent-dir", type=Path, default=PARENT, help=argparse.SUPPRESS)
    args = parser.parse_args()
    parent = args.parent_dir.resolve()

    changes, problems = plan(parent, find_skills(parent))
    for problem in problems:
        print(f"problem: {problem}", file=sys.stderr)
    for action, path, payload in changes:
        rel = path.relative_to(parent).as_posix()
        if args.check:
            print(f"out of date ({action}): {rel}")
            continue
        if action == "stale" and not args.prune:
            print(f"stale, kept (use --prune to remove): {rel}")
            continue
        print(f"{action}: {rel}")
        path.parent.mkdir(parents=True, exist_ok=True)
        if action in ("relink", "stale"):
            path.unlink()
        if action == "write":
            path.write_text(payload, encoding="utf-8")
        elif action in ("link", "relink"):
            path.symlink_to(payload)
    if not changes and not problems:
        print("parent folder is up to date")
    if args.check:
        return 1 if changes or problems else 0
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
