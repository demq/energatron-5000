def list_body(plans: Sequence[Mapping[str, Any]]) -> bytes:
    """A CDR plan-list page holding every plan's header fields."""
    document = {
        "data": {"plans": [{key: plan[key] for key in _LIST_KEYS if key in plan} for plan in plans]},
        "links": {"self": f"demo://{DEMO_BASE}/plans"},
        "meta": {"totalRecords": len(plans), "totalPages": 1},
    }
    return json.dumps(document).encode("utf-8")


def detail_body(plan: Mapping[str, Any]) -> bytes:
    """A CDR plan-detail body: `{data, links, meta}`."""
    document = {"data": dict(plan), "links": {"self": f"demo://{DEMO_BASE}/plans/{plan['planId']}"}, "meta": {}}
    return json.dumps(document).encode("utf-8")


# The build


def _write(folder: Path, name: str, data: bytes) -> Path:
    path = folder / name
    atomic_write_bytes(path, data)
    return path


def _landed(ctx: ServiceContext, paths: Sequence[Path], source: SourceType | None = None) -> tuple[list[str], int]:
    """Land `paths`: their dataset IDs in order and the commits made (0 or 1). A rejection fails the demo (a bug)."""
    result = land_service.land(ctx, list(paths), source=source)
    error = land_service.outcome(result)
    if error is not None:
        raise error
    ids = [item.dataset_id for item in sorted(result.items, key=lambda item: item.position)]
    if any(ident is None for ident in ids):
        raise InternalError("A demo file didn't land.")
    return [ident for ident in ids if ident is not None], int(result.commit is not None)


def build(ctx: ServiceContext, *, tool: ToolState, provider: OfferProvider) -> DemoResult:
    """Generate, land, fetch and run the demo (P8 spec §5.1). The caller holds the workspace lock."""
    if ctx.private is None or ctx.private.premises.nmi != DEMO_NMI11:
        raise UsageError(
            "energatron demo runs only in a workspace made by `energatron init --demo`.", reason="not_demo"
        )
    root = ctx.paths.root
    folder = root / LANDING
    try:
        make_dirs(folder)
        days = meter_days()
        meter = _write(folder, nem12_filename(), nem12(days))
        usage = _write(folder, "demo_usage_export.csv", usage_export(days, ctx.region))
        periods = gas_periods()
        pdfs = [
            _write(folder, f"demo_gas_bill_{start:%Y%m}.pdf", gas_bill_pdf(end + timedelta(days=4)))
            for start, end in periods
        ]
    except OSError:
        raise InternalError("The demo files couldn't be written.") from None
    landed, commits = _landed(ctx, [meter, usage])
    pdf_ids, made = _landed(ctx, pdfs, SourceType.GAS_BILL)
    commits += made
    records: list[Path] = []
    index = 1000
    for (start, end), pdf_id in zip(periods, pdf_ids, strict=True):
        record = gas_bill_record((start, end), index, pdf_id)
        index += _GAS_VOLUMES[start.month]
        records.append(_write(folder, f"gas_bill_record-{start:%Y%m}.yaml", record_yaml(record)))
    record_ids, made = _landed(ctx, records)
    landed += pdf_ids + record_ids
    commits += made
    for path in (meter, usage, *pdfs, *records):  # the demo's own copies; every byte is in the raw zone now
        path.unlink()
    if not any(folder.iterdir()):
        folder.rmdir()

    fetched = fetch_service.fetch_offers(replace(ctx, offers={"cdr": provider}), retailers=[DEMO_BASE])
    failure: EnergatronError | None = fetch_service.outcome(fetched)
    if failure is not None:
        raise failure
    commits += int(fetched.commit is not None)
    ran = run_service.run(ctx, tool=tool)
    commits += 1
    _log.info("demo: %d datasets landed, run %s", len(landed), ran.run_id)
    return DemoResult(
        landed=len(landed),
        offers=len(fetched.landed),
        run_id=ran.run_id,
        recommendation_id=ran.recommendation_id,
        reports=list(REPORTS),
        commits=commits,
    )
