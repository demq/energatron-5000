DEMO_ACCOUNT: Final = "990000000001"
DEMO_BASE: Final = "demo"
"""The frozen offer set's CDR base URI."""
FIRST_DAY: Final = date(2025, 9, 1)
LAST_DAY: Final = date(2026, 10, 31)
