# Meter data


def _days() -> list[date]:
    return [FIRST_DAY + timedelta(days=offset) for offset in range((LAST_DAY - FIRST_DAY).days + 1)]


def _day_values(rng: random.Random, day: date) -> list[float]:
    """A household's half-hours: low overnight, a morning and an evening peak; more in winter and summer."""
    season = 1.0 + 0.35 * (day.month in (6, 7, 8)) + 0.2 * (day.month in (12, 1, 2))
    weekend = 1.15 if day.weekday() >= 5 else 1.0
    values: list[float] = []
    for index in range(1440 // INTERVAL_MINUTES):
        hour = index * INTERVAL_MINUTES / 60
        shape = 0.15 if hour < 6 else 0.55 if hour < 9 else 0.3 if hour < 16 else 0.8 if hour < 22 else 0.25
        values.append(round((0.05 + shape * (0.6 + 0.8 * rng.random())) * season * weekend / 2, 3))
    return values


def meter_days() -> dict[date, list[float]]:
    """Every meter date's interval values (kWh), deterministic."""
    rng = random.Random(SEED)
    return {day: _day_values(rng, day) for day in _days()}


def nem12(days: Mapping[date, Sequence[float]]) -> bytes:
    """A NEM12 file as SAPN writes its downloads: one `200`, a `300` per day, then `900` (D3 §5.2)."""
    rows = [f"200,{DEMO_NMI},E1,1,E1,E1,{DEMO_SERIAL},KWH,{INTERVAL_MINUTES},"]
    for day, values in days.items():
        stamp = f"{datetime.combine(day + timedelta(days=1), time(5, 0)):%Y%m%d%H%M%S}"
        rows.append(f"300,{day:%Y%m%d},{','.join(f'{value:.3f}' for value in values)},A,,,{stamp},{stamp}")
    rows.append("900")
    return "".join(row + "\n" for row in rows).encode("utf-8")


def nem12_filename() -> str:
    return f"{DEMO_NMI11}_{FIRST_DAY:%Y%m%d}_{LAST_DAY:%Y%m%d}_{GENERATED:%Y%m%d%H%M%S}_SAPN_DETAILED.csv"


def _minutes(text: str) -> int:
    hours, minutes = text.split(":")
    return int(hours) * 60 + int(minutes)


def _label(minute: int, windows: Mapping[str, Sequence[str]]) -> str:
    for label, spans in windows.items():
        for span in spans:
            start, end = (_minutes(part) for part in span.split("-"))
            if (start <= minute < end) if start < end else (minute >= start or minute < end):
                return label
    raise InternalError("The region's TOU windows don't cover a minute of the day.")


def usage_export(days: Mapping[date, Sequence[float]], profile: RegionProfile) -> bytes:
    """A retailer portal usage export computed from the meter data as a retailer billing on NEM time would (D3 §5.4).

    One row per monthly read at midnight; each covers the meter dates after the previous read up to and including the
    read's date, split by the region's TOU windows at local time.
    """
    windows = profile.tou_windows
    if windows is None or profile.local_tz is None:
        raise InternalError("The region profile has no TOU windows or time zone.")
    zone = ZoneInfo(profile.local_tz)
    labels = sorted(windows)
    reads = [date(year, month, 1) for year, month in _months(FIRST_DAY, LAST_DAY)][1:]
    header = ["Account Code", "Read Datetime", *(f"E1 ({DEMO_SERIAL} - {label})" for label in labels), "Total"]
    lines = [",".join(header)]
    previous: date | None = None
    for read in reads:
        sums = dict.fromkeys(labels, Decimal(0))
        for day, values in days.items():
            if (previous is not None and day <= previous) or day > read:
                continue
            for index, value in enumerate(values):
                meter = datetime.combine(day, time()) + timedelta(minutes=index * INTERVAL_MINUTES)
                local = (meter - _NEM_OFFSET).replace(tzinfo=UTC).astimezone(zone)
                sums[_label(local.hour * 60 + local.minute, windows)] += Decimal(f"{value:.3f}")
        total = sum(sums.values(), Decimal(0))
        cells = [f"{sums[label]:.4f}" for label in labels] + [f"{total:.4f}"]
        lines.append(",".join([DEMO_ACCOUNT, f"{read:%Y-%m-%d}T00:00:00", *cells]))
        previous = read
    return "".join(line + "\r\n" for line in lines).encode("utf-8")


def _months(first: date, last: date) -> list[tuple[int, int]]:
    found: list[tuple[int, int]] = []
    year, month = first.year, first.month
    while (year, month) <= (last.year, last.month):
        found.append((year, month))
        year, month = (year + 1, 1) if month == 12 else (year, month + 1)
    return found


# Gas bills

_HEATING_VALUE: Final = Decimal("38.5000")
_PRESSURE_FACTOR: Final = Decimal("1.0100")
_GAS_USAGE_RATE: Final = Decimal("0.04200")
_GAS_SUPPLY_RATE: Final = Decimal("0.85000")
_GST: Final = Decimal("0.10")
_GAS_VOLUMES: Final = {1: 22, 2: 20, 3: 26, 4: 40, 5: 62, 6: 84, 7: 92, 8: 86, 9: 60, 10: 42, 11: 30, 12: 24}
"""Cubic metres per month: heating in winter."""


def _money(value: Decimal) -> Decimal:
    return value.quantize(_CENT, rounding=ROUND_HALF_UP)


def gas_periods() -> list[tuple[date, date]]:
    """Twelve calendar-month bills, November to October."""
    found: list[tuple[date, date]] = []
    for year, month in _months(date(2025, 11, 1), date(2026, 10, 1)):
        start = date(year, month, 1)
        following = date(year + 1, 1, 1) if month == 12 else date(year, month + 1, 1)
        found.append((start, following - timedelta(days=1)))
    return found


def gas_bill_pdf(issue: date) -> bytes:
    """A minimal one-page PDF whose creation date is the bill's issue date (the bill parser's fallback date)."""
    content = b"BT /F1 12 Tf 72 720 Td (Synthetic demo gas bill) Tj ET"
    objects = {
        1: b"<< /Type /Catalog /Pages 2 0 R >>",
        2: b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        3: b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R"
        b" /Resources << /Font << /F1 6 0 R >> >> >>",
        4: b"<< /Length " + str(len(content)).encode() + b" >>\nstream\n" + content + b"\nendstream",
        5: f"<< /Producer (energatron demo) /CreationDate (D:{issue:%Y%m%d}120000+10'30') >>".encode(),
        6: b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    }
    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets: dict[int, int] = {}
    for number, body in objects.items():
        offsets[number] = len(out)
        out.extend(f"{number} 0 obj\n".encode() + body + b"\nendobj\n")
    xref = len(out)
    out.extend(f"xref\n0 {len(objects) + 1}\n0000000000 65535 f \n".encode())
    out.extend(b"".join(f"{offsets[number]:010d} 00000 n \n".encode() for number in sorted(objects)))
    out.extend(f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R /Info 5 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode())
    return bytes(out)


def gas_bill_record(period: tuple[date, date], start_index: int, pdf_dataset_id: str) -> dict[str, Any]:
    """A `gas_bill_record` whose read, lines and totals agree, as the `gas_bills` checks recompute them (P5 spec)."""
    start, end = period
    volume = _GAS_VOLUMES[start.month]
    mj = (Decimal(volume) * _HEATING_VALUE * _PRESSURE_FACTOR).quantize(_CENT, rounding=ROUND_HALF_UP)
    days = (end - start).days + 1
    usage = _money(mj * _GAS_USAGE_RATE)
    supply = _money(Decimal(days) * _GAS_SUPPLY_RATE)
    subtotal = usage + supply
    gst = _money(subtotal * _GST)
    return {
        "kind": "gas_bill_record",
        "schema_version": 2,
        "pdf_dataset_id": pdf_dataset_id,
        "extracted_by": "manual",  # made by code, not by an agent (P9 spec §4.3)
        "retailer": "Demo Gas Co",
        "plan_name": "Demo Gas Everyday",
        "issue_date": (end + timedelta(days=4)).isoformat(),
        "period_start": start.isoformat(),
        "period_end": end.isoformat(),
        "reads": [
            {
                "date": end.isoformat(),
                "type": "actual",
                "start": str(start_index),
                "end": str(start_index + volume),
                "heating_value": str(_HEATING_VALUE),
                "pressure_factor": str(_PRESSURE_FACTOR),
                "mj": str(mj),
            }
        ],
        "lines": [
            {
                "line": "usage",
                "label": "Gas usage",
                "quantity": str(mj),
                "unit": "MJ",
                "rate": str(_GAS_USAGE_RATE),
                "amount": str(usage),
            },
            {
                "line": "supply",
                "label": "Supply charge",
                "quantity": str(days),
                "unit": "day",
                "rate": str(_GAS_SUPPLY_RATE),
                "amount": str(supply),
            },
        ],
        "subtotal": str(subtotal),
        "gst": str(gst),
        "total": str(subtotal + gst),
    }


def record_yaml(record: Mapping[str, Any]) -> bytes:
    """The record as YAML, `kind` and `schema_version` first as plain lines (how `land` recognises it); every other
    value is double-quoted, so dates and amounts stay strings."""
    rest = {key: value for key, value in record.items() if key not in ("kind", "schema_version")}
    head = f"kind: {record['kind']}\nschema_version: {record['schema_version']}\n"
    return (head + yaml.safe_dump(rest, default_style='"', sort_keys=False, allow_unicode=True)).encode("utf-8")


