def demo_plans(profile: RegionProfile) -> list[dict[str, Any]]:
    """The frozen offer set: three electricity and two gas plans from two invented brands, for the region's
    distributors. Prices are invented too (GST-inclusive dollars, as the CDR publishes them)."""
    elec, gas = profile.distributor, profile.gas_distributor
    if elec is None or gas is None:
        raise InternalError("The region profile has no distributor or gas distributor.")
    membership = {"type": "MEMBERSHIP", "term": "ANNUAL", "amount": "60.00", "description": "A made-up fee."}
    return [
        _elec_plan("DEMO-FLAT@DEMO", "sunbeam-power", "Sunbeam Flat", elec, _single("0.3800", "1.1000")),
        _elec_plan(
            "DEMO-TOU@DEMO",
            "sunbeam-power",
            "Sunbeam Time Saver",
            elec,
            _time_of_use("0.5200", "0.3000", "0.2200", "1.0500"),
        ),
        _elec_plan(
            "DEMO-CLUB@DEMO", "gumleaf-energy", "Gumleaf Club", elec, _single("0.3300", "1.0000"), fees=[membership]
        ),
        _gas_plan("DEMO-GAS-STD@DEMO", "sunbeam-power", "Sunbeam Gas", gas, "0.0450", "0.9000"),
        _gas_plan("DEMO-GAS-LOW@DEMO", "gumleaf-energy", "Gumleaf Gas", gas, "0.0400", "0.9500"),
    ]


