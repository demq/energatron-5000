"""The workspace's `dvc.yaml`, generated from the registered stages (D1 §9.5; D3 §10.1).

`energatron stage --emit-dvc-yaml` prints it and `energatron pipeline sync` writes it. The golden copy is
`tests/fixtures/golden/dvc.yaml`; changing it is a deliberate part of any change to `STAGES`.
"""

from collections.abc import Mapping
from typing import ClassVar, Final, Literal

import yaml

from energatron.services.context import ServiceResult
from energatron.services.stages.runner import StageSpec

HEADER: Final = "# Generated by energatron pipeline sync. Do not edit; re-run the command instead.\n"
CODE_FINGERPRINT_PATH: Final = ".energatron/code_fingerprint.json"
"""The workspace-relative fingerprint file; each stage tracks only its own `stage_sha256` in it (D1 §11)."""


def stage_entry(spec: StageSpec) -> dict[str, object]:
    """One stage's `dvc.yaml` entry: its command, declared inputs, params plus its own code entry, and outputs.

    Outputs use DVC's default caching: `cache: false` is never emitted.
    """
    entry: dict[str, object] = {"cmd": f"energatron stage {spec.name}"}
    if spec.inputs:
        entry["deps"] = list(spec.inputs.values())
    entry["params"] = [*spec.params, {CODE_FINGERPRINT_PATH: [f"stages.{spec.name}.stage_sha256"]}]
    entry["outs"] = list(spec.outputs.values())
    return entry


def emit_dvc_yaml(stages: Mapping[str, StageSpec]) -> str:
    """The `dvc.yaml` text for `stages`, in their order: the header line, then `yaml.safe_dump(sort_keys=False)`."""
    body = {"stages": {name: stage_entry(spec) for name, spec in stages.items()}}
    return HEADER + yaml.safe_dump(body, sort_keys=False)


class DvcYamlResult(ServiceResult):
    """`dvc_yaml_result` v1: what `energatron stage --emit-dvc-yaml --json` returns, the generated text (P1.3.3)."""

    KIND: ClassVar[str] = "dvc_yaml_result"
    SCHEMA_VERSION: ClassVar[int] = 1
    kind: Literal["dvc_yaml_result"] = "dvc_yaml_result"
    schema_version: Literal[1] = 1

    text: str
